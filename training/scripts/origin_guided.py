"""Optional grammar for the bounded return-expression pilot, shared by both LoRAs.

Only syntax and the exposed tool contract are constrained. Operators, constants,
paths, choice of tool and final answer are still generated by the model.
"""
from __future__ import annotations

GUIDANCE = {"library": "lm-format-enforcer", "version": "0.11.3", "grammar": "bounded-return-tools-v2"}
# Match the executable identifier whitelist. Arbitrary English words inflate
# token-tree traversal and would be refused by the tool guard in any case.
RETURN_PATTERN = r"^return (value|Math|min|max|true|false|[0-9]|[ .,()<>=?:+*\-!&|])+;$"


def tool_parser(alphabet: str, include_text: bool = True):
    from lmformatenforcer import JsonSchemaParser, RegexParser
    from lmformatenforcer.characterlevelparser import CharacterLevelParserConfig, SequenceParser, StringParser, UnionParser
    class ToolSequence(SequenceParser):
        def add_character(self, character):
            def wrap(parser):
                if isinstance(parser, SequenceParser): return ToolSequence(parser.parsers)
                if isinstance(parser, UnionParser): return UnionParser([wrap(p) for p in parser.parsers])
                return parser
            return wrap(super().add_character(character))

        def shortcut_key(self):
            # Keep LMFE's JSON-string token cache available through the closing
            # tool delimiter. The delimiter cannot begin until JSON can end.
            first = self.parsers[0]
            return first.shortcut_key() if not first.can_end() else None
    config = CharacterLevelParserConfig(alphabet=alphabet)
    schemas = {
        "read_file": {"path": {"type": "string"}},
        "edit_file": {"path": {"type": "string"}, "old_string": {"type": "string", "enum": ["return value;"]},
                      "new_string": {"type": "string", "pattern": RETURN_PATTERN}},
        "run_shell": {"command": {"type": "string", "enum": ["node --test"]}},
    }
    choices = [RegexParser(r"[^<]+", config)] if include_text else []
    for name, properties in schemas.items():
        schema = {"type": "object", "properties": properties, "required": list(properties), "additionalProperties": False}
        choices.append(ToolSequence([StringParser(f'<tool name="{name}">\n'), JsonSchemaParser(schema, config), StringParser('\n</tool>')]))
    return UnionParser(choices)


class GuidedTools:
    def __init__(self, tokenizer):
        from importlib.metadata import version
        from origin_dataset import require
        require(version("lm-format-enforcer") == GUIDANCE["version"], "Use the pinned grammar library")
        from lmformatenforcer.integrations.transformers import build_token_enforcer_tokenizer_data
        self.data = build_token_enforcer_tokenizer_data(tokenizer)
        # Traversing the entire vocabulary through a union of free text and
        # nested JSON is expensive. Free text has a constant token mask; only
        # the tool branch needs the character parser. The first token chooses
        # the branch, using the same model scores and no task-specific answer.
        self.text_tokens = [token for token, text, _ in self.data.regular_tokens if "<" not in text]
        eos = self.data.eos_token_id
        self.end_tokens = eos if isinstance(eos, list) else [eos]

    def prefix(self):
        from lmformatenforcer.integrations.transformers import build_transformers_prefix_allowed_tokens_fn
        tools = build_transformers_prefix_allowed_tokens_fn(self.data, tool_parser(self.data.tokenizer_alphabet, include_text=False))
        prompt_size = None
        initial_tools = None
        def allowed(batch_id, sent):
            nonlocal prompt_size, initial_tools
            if prompt_size is None:
                prompt_size = len(sent)
                initial_tools = tools(batch_id, sent)
                return list(set(self.text_tokens) | set(initial_tools))
            if int(sent[prompt_size]) in initial_tools:
                return tools(batch_id, sent)
            return self.text_tokens + self.end_tokens
        return allowed
