// Controlled continuation after an edit failure, using real Agent/Tools messages.
// The initial read and rejected edit are fixtures, never supervised targets.
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { Agent } from "../src/agent.ts";
import { formatToolCall } from "../src/protocol.ts";
import { createOriginProvider, originMessages } from "../src/providers/origin.ts";
import type { AgentEvent, Provider } from "../src/types.ts";
import { curriculumTools, recipe, runPractice, sha } from "./model-curriculum.ts";

export function recoveryRecipe(seed: number) {
  if (!Number.isInteger(seed) || seed < 0 || seed > 9999) throw new Error("Seed must be 0..9999");
  const task = recipe(seed);
  const oldString = seed % 2 === 0 ? "return value + 0;" : "return 0 + value;";
  // An equivalent external edit invalidates the original replacement string.
  const refreshed = task.before.replace(task.oldString, oldString);
  return { ...task, oldString, refreshed, taskId: `origin-recovery-${seed}` };
}

export async function runRecovery(seed: number, provider?: Provider, split: "train" | "validation" | "tune" = "tune", onEvent?: (event: AgentEvent) => void) {
  const task = recoveryRecipe(seed);
  const parent = resolve(process.env.ORIGIN_PRACTICE_PARENT ?? tmpdir());
  await mkdir(parent, { recursive: true });
  const root = process.env.ORIGIN_PRACTICE_PARENT
    ? join(parent, `origin-recovery-practice-${seed}`)
    : await mkdtemp(join(parent, "origin-recovery-practice-"));
  if (process.env.ORIGIN_PRACTICE_PARENT) await mkdir(root);
  const examples: unknown[] = [];
  const events: AgentEvent[] = [];
  let step = 0;
  let injected = false;
  let reread = false;
  const actions = [
    formatToolCall("read_file", { path: task.path }),
    formatToolCall("edit_file", { path: task.path, old_string: recipe(seed).oldString, new_string: task.newString }),
    formatToolCall("read_file", { path: task.path }),
    formatToolCall("edit_file", { path: task.path, old_string: task.oldString, new_string: task.newString }),
    formatToolCall("run_shell", { command: "node --test" }),
    "更新後のファイルを読み直して実装を変更し、テストの通過を確認しました。",
  ];
  const continuation: Provider = {
    name: provider?.name ?? "curated-recovery", contextBudget: provider?.contextBudget,
    complete: async (messages, tools, env, callbacks) => {
      const index = step++;
      // Both variants receive the same failed-operation prefix. Only continuation
      // actions (re-read/edit/test/answer) are generated by the evaluated model.
      if (index < 2) return actions[index]!;
      if (provider) return provider.complete(messages, tools, env, callbacks);
      const answer = actions[index];
      if (!answer) throw new Error("Recovery demonstration did not finish");
      examples.push({ version: 1, kind: "sft", id: sha(`${split}:${task.taskId}:${index}`), split,
        task_id: task.taskId, messages: [...originMessages(messages, tools, env), { role: "assistant", content: answer }],
        metadata: { representation: "provider_messages", outcome: "success", cleaned: true,
          source: { provider: "curated-recovery", report_completion: "completed", recipe_sha256: sha(JSON.stringify(task)),
            failure_fixture: "concurrent_equivalent_edit", target_origin: "verified_recovery_continuation" } } });
      return answer;
    },
  };
  const tools = curriculumTools.map((tool) => ({ ...tool, run: async (args: Record<string, unknown>, ctx: Parameters<typeof tool.run>[1]) => {
    if (tool.name === "edit_file") {
      if (args.path !== task.path) throw new Error("Only the specified source file may be edited");
      if (!injected) {
        await writeFile(join(root, task.path), task.refreshed);
        injected = true;
        throw new Error("ファイルが別の操作で更新され、old_string が一致しません。read_file で現在の内容を読み直し、その実物に一致する old_string で編集してください。ファイルは編集していません。");
      }
    }
    const result = await tool.run(args, ctx);
    if (tool.name === "read_file" && injected && args.path === task.path) reread = true;
    return result;
  } }));
  const started = Date.now();
  let ok = false;
  let reason: string | undefined;
  let sourceAfter: string | undefined;
  try {
    await mkdir(join(root, "src")); await mkdir(join(root, "test"));
    await writeFile(join(root, "package.json"), '{"type":"module"}\n');
    await writeFile(join(root, task.path), task.before);
    await writeFile(join(root, task.testFile), task.tests);
    const agent = new Agent({ provider: continuation, tools, mode: "code", maxSteps: 7,
      ctx: { root, confirm: async (message) => !message.startsWith("コマンドを実行します:") || message === "コマンドを実行します: node --test" } });
    await agent.run(task.input, (event) => { events.push(event); onEvent?.(event); });
    sourceAfter = await readFile(join(root, task.path), "utf8");
    if (!injected || !reread) throw new Error("Did not re-read the source after the edit failure");
    if (await readFile(join(root, task.testFile), "utf8") !== task.tests) throw new Error("Test file changed");
    if (!(await readFile(join(root, task.path), "utf8")).includes("export function neighbor(value) { return value - 1; }")) throw new Error("Unrelated neighbor changed");
    const checkEnv = { ...process.env }; delete checkEnv.NODE_TEST_CONTEXT;
    const checked = await promisify(execFile)(process.execPath, ["--test", "--test-reporter=tap"], { cwd: root, env: checkEnv, windowsHide: true, timeout: 20_000 });
    if (!/tests 1/.test(checked.stdout) || !/pass 1/.test(checked.stdout)) throw new Error("Expected test did not run");
    if (!events.some((event) => event.type === "tool_end" && event.name === "run_shell" && event.ok)) throw new Error("Model did not run a passing test");
    const done = events.at(-1);
    if (done?.type !== "done" || done.reason !== "answered") throw new Error("Model did not complete the continuation");
    ok = true;
  } catch (error) { reason = error instanceof Error ? error.message : String(error); }
  finally { await rm(root, { recursive: true, force: true }); }
  if (!provider && !ok) throw new Error(`Recovery demonstration failed verification: ${reason}`);
  return { task_id: task.taskId, ok, ms: Date.now() - started, reason, events, examples, sourceAfter };
}

async function main() {
  const [mode, output, variant = "baseline", countText = "2"] = process.argv.slice(2);
  if (!output || !["generate", "evaluate"].includes(mode ?? "")) throw new Error("Usage: recovery-curriculum.ts generate <new-directory> | evaluate <report.json> baseline|candidate [1..20]");
  if (mode === "generate") {
    const train: unknown[] = []; const validation: unknown[] = [];
    for (const [split, affineSeeds, recoverySeeds, records] of [
      ["train", [0, 1, 2, 3, 4, 5], [20, 21, 22, 23], train],
      ["validation", [100, 101], [120, 121], validation],
    ] as const) {
      for (const seed of affineSeeds) records.push(...(await runPractice(seed, undefined, split)).examples);
      for (const seed of recoverySeeds) records.push(...(await runRecovery(seed, undefined, split)).examples);
    }
    // Publish only after every demonstration passes. Refuse existing runs.
    await mkdir(output, { recursive: false });
    await writeFile(join(output, "train.jsonl"), train.map((record) => JSON.stringify(record)).join("\n") + "\n", { flag: "wx" });
    await writeFile(join(output, "validation.jsonl"), validation.map((record) => JSON.stringify(record)).join("\n") + "\n", { flag: "wx" });
    console.log(JSON.stringify({ verified: true, train_examples: train.length, validation_examples: validation.length }));
  } else {
    const count = Number(countText);
    if (!Number.isInteger(count) || count < 1 || count > 20) throw new Error("Task count must be 1..20");
    const provider = createOriginProvider({ variant });
    const attempts = [];
    for (let index = 0; index < count; index++) {
      const { examples: _examples, ...attempt } = await runRecovery(200 + index, provider);
      attempts.push(attempt);
      console.log(JSON.stringify({ variant, index, ok: attempt.ok, ms: attempt.ms }));
    }
    await mkdir(resolve(output, ".."), { recursive: true });
    await writeFile(output, JSON.stringify({ version: 1, completed: true, split: "tune", variant,
      scope: "controlled_edit_failure_continuation", fixture_steps: 2, tools: curriculumTools.map((tool) => tool.name), max_steps: 7,
      recipe_sha256: sha(JSON.stringify(Array.from({ length: count }, (_, index) => recoveryRecipe(200 + index)))),
      passed: attempts.filter((attempt) => attempt.ok).length, total: count, attempts }, null, 2) + "\n", { flag: "wx" });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) await main().catch((error: unknown) => { console.error(error instanceof Error ? error.message : String(error)); process.exitCode = 1; });
